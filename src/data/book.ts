export function getProcess(processId: string | undefined): ProcessModule | null {
  if (!processId) {
    return null;
  }
  return PROCESSES.find((processModule) => processModule.id === processId) ?? null;
}

export function homeAlerts(): { processId: string; alert: ProcessModule["alerts"][number] }[] {
  return PROCESSES.flatMap((processModule) =>
    processModule.alerts
      .filter((alert) => alert.pinToHome)
      .map((alert) => ({ processId: processModule.id, alert })),
  );
}

export function homeTodos(): { processId: string; todo: ProcessModule["todos"][number]; rank: number }[] {
  const pinned = PROCESSES.flatMap((processModule) =>
    processModule.todos
      .filter((todo) => todo.pinToHome)
      .map((todo) => ({ processId: processModule.id, todo })),
  );
  return pinned.map((item, index) => ({ ...item, rank: index + 1 }));
}
