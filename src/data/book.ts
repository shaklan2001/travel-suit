function assertFleetMatchesSquad(): void {
  const squadIds = corporateAgents.map((agent) => agent.id);
  const fleetKeys = FLEET.map((agent) => agent.key);
  const sameLength = squadIds.length === fleetKeys.length;
  const sameOrder = squadIds.every((id, index) => id === fleetKeys[index]);
  if (!sameLength || !sameOrder) {
    throw new Error("Corporate squad is out of order with the email fleet.");
  }
}

assertFleetMatchesSquad();

